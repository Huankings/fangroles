/**
 * fangroles 的配置实现区。
 *
 * <h2>配置放哪一层</h2>
 * <ul>
 *   <li><b>跨世界 / 全服唯一配置</b> → CCA scoreboard 组件，
 *       例如「本模组全局开关」。</li>
 *   <li><b>随存档 / 随世界生效的配置</b> → CCA world 组件，
 *       例如「本局是否启用某机制」。</li>
 *   <li><b>玩家本地偏好</b>（客户端显示开关）→ 客户端配置，
 *       参考 NoellesRoles 用 YACL 的做法。</li>
 * </ul>
 *
 * <h2>默认值放哪里</h2>
 * <p>玩法默认值（冷却、概率、阈值）不要写死在配置类里，
 * 应该放对应职业的 {@code *Constants}，配置只负责「覆盖默认值」。
 * 否则后续调平衡要同时改两处。</p>
 *
 * <h2>运行时切换的清理要求</h2>
 * <p>如果某个开关会改变玩法行为，切换时必须考虑：
 * <ul>
 *   <li>已生效的职业状态是否需要立即回收（临时物品、护盾、音乐）。</li>
 *   <li>是否需要同步给所有客户端（世界组件配置必须变化时同步一次，
 *       不要在 tick 里无条件 sync）。</li>
 *   <li>是否要写回放（影响玩法的开关切换通常应该记录）。</li>
 * </ul>
 */
package org.agmas.fangroles.config;
